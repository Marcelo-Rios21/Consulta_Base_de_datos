-- FUNCION DE VERIFICACION
CREATE OR REPLACE FUNCTION ADMIN.PRY2205_VERIFY_PASSWORD (
    p_username     VARCHAR2,
    p_password     VARCHAR2,
    p_old_password VARCHAR2
) RETURN BOOLEAN IS
BEGIN
    IF p_password IS NULL OR LENGTH(p_password) < 12 THEN
        raise_application_error(-20001, 'Password: mínimo 12 caracteres.');
    END IF;

    IF REGEXP_COUNT(p_password, '[a-z]') < 1 THEN
        raise_application_error(-20002, 'Password: mínimo 1 minúscula.');
    END IF;

    IF REGEXP_COUNT(p_password, '[A-Z]') < 2 THEN
        raise_application_error(-20003, 'Password: mínimo 2 mayúsculas.');
    END IF;

    IF REGEXP_COUNT(p_password, '[0-9]') < 2 THEN
        raise_application_error(-20004, 'Password: mínimo 2 números.');
    END IF;

    IF INSTR(UPPER(p_password), UPPER(p_username)) > 0 THEN
        raise_application_error(-20005, 'Password: no puede contener el nombre del usuario.');
    END IF;

    RETURN TRUE;
END;

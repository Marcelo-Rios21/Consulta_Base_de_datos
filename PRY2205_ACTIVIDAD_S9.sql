CREATE OR REPLACE VIEW VW_EMPRESAS_ASESORADAS AS
SELECT
  TO_CHAR(q.RUT_EMPRESA, 'FM999G999G999', 'NLS_NUMERIC_CHARACTERS='',.''')
  || '-' || q.DV_EMPRESA                                              AS RUT_EMPRESA,

  UPPER(q.NOMBRE_EMPRESA)                                             AS NOMBRE_EMPRESA,

  ROUND(q.IVA_DECLARADO, 0)                                           AS IVA,

TRUNC(
  MONTHS_BETWEEN(
    (ADD_MONTHS(TRUNC(SYSDATE,'YYYY'), 12) - 1),  
    q.FECHA_INICIO_ACT
  ) / 12
) AS ANIOS_EXISTENCIA,


  TRUNC(q.TOTAL_ASESORIAS_ANIO / 12)                                  AS TOTAL_ASESORIAS_ANUALES,

  TRUNC(
    q.IVA_DECLARADO * (TRUNC(q.TOTAL_ASESORIAS_ANIO / 12) / 100)
  )                                                                   AS DEVOLUCION_IVA,

  CASE
    WHEN TRUNC(q.TOTAL_ASESORIAS_ANIO / 12) > 5 THEN 'CLIENTE PREMIUM'
    WHEN TRUNC(q.TOTAL_ASESORIAS_ANIO / 12) BETWEEN 3 AND 5 THEN 'CLIENTE'
    ELSE 'CLIENTE POCO CONCURRIDO'
  END                                                                 AS TIPO_CLIENTE,

-- PREMIUM => 1 ASESORIA GRATIS, resto => CAPTAR CLIENTE
  CASE
    WHEN TRUNC(q.TOTAL_ASESORIAS_ANIO / 12) > 5 THEN '1 ASESORIA GRATIS'
    ELSE 'CAPTAR CLIENTE'
  END                                                                 AS CORRESPONDE

FROM (
  SELECT
    e.RUT_EMPRESA                    AS RUT_EMPRESA,
    e.DV_EMPRESA                     AS DV_EMPRESA,
    e.NOMEMPRESA                     AS NOMBRE_EMPRESA,
    e.IVA_DECLARADO                  AS IVA_DECLARADO,
    e.FECHA_INICIACION_ACTIVIDADES   AS FECHA_INICIO_ACT,
    COUNT(*)                         AS TOTAL_ASESORIAS_ANIO
  FROM S_EMPRESA e
  JOIN S_ASESORIA a
    ON a.IDEMPRESA = e.IDEMPRESA
  WHERE
    a.FIN >= ADD_MONTHS(TRUNC(SYSDATE, 'YYYY'), -12)
    AND a.FIN <  TRUNC(SYSDATE, 'YYYY')
  GROUP BY
    e.RUT_EMPRESA,
    e.DV_EMPRESA,
    e.NOMEMPRESA,
    e.IVA_DECLARADO,
    e.FECHA_INICIACION_ACTIVIDADES
) q;

COMMIT;


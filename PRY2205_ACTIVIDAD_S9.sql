-- INSERCION A LA CARTOLA
INSERT INTO PRY2205_EFT.CARTOLA_PROFESIONALES
(
  RUT_PROFESIONAL,
  NOMBRE_PROFESIONAL,
  PROFESION,
  ISAPRE,
  SUELDO_BASE,
  PORC_COMISION_PROFESIONAL,
  VALOR_TOTAL_COMISION,
  PORCENTATE_HONORARIO,
  BONO_MOVILIZACION,
  TOTAL_PAGAR
)
SELECT
  p.RUTPROF AS rut_profesional,

  (p.NOMPRO || ' ' || p.APPPRO || ' ' || p.APMPRO) AS nombre_profesional,

  pr.NOMPROFESION AS profesion,
  i.NOMISAPRE     AS isapre,

  ROUND(p.SUELDO,0) AS sueldo_base,

  NVL(p.COMISION,0) AS porc_comision_profesional,

  ROUND(ROUND(p.SUELDO,0) * NVL(p.COMISION,0), 0) AS valor_total_comision,

  CASE
    WHEN tc.NOMTCONTRATO = 'Honorarios'
      THEN ROUND(ROUND(p.SUELDO,0) * (NVL(rs.HONOR_PCT,0) / 100), 0)
    ELSE 0
  END AS porcentate_honorario,

  CASE tc.NOMTCONTRATO
    WHEN 'Indefinido Jornada Completa' THEN 150000
    WHEN 'Indefinido Jornada Parcial'  THEN 120000
    WHEN 'Plazo fijo'                  THEN 60000
    WHEN 'Honorarios'                  THEN 50000
    ELSE 0
  END AS bono_movilizacion,

  ROUND(p.SUELDO,0)
  + ROUND(ROUND(p.SUELDO,0) * NVL(p.COMISION,0), 0)
  + CASE
      WHEN tc.NOMTCONTRATO = 'Honorarios'
        THEN ROUND(ROUND(p.SUELDO,0) * (NVL(rs.HONOR_PCT,0) / 100), 0)
      ELSE 0
    END
  + CASE tc.NOMTCONTRATO
      WHEN 'Indefinido Jornada Completa' THEN 150000
      WHEN 'Indefinido Jornada Parcial'  THEN 120000
      WHEN 'Plazo fijo'                  THEN 60000
      WHEN 'Honorarios'                  THEN 50000
      ELSE 0
    END AS total_pagar
FROM S_PROFESIONAL p
JOIN S_PROFESION pr
  ON pr.IDPROFESION = p.IDPROFESION
JOIN S_ISAPRE i
  ON i.IDISAPRE = p.IDISAPRE
LEFT JOIN S_TIPO_CONTRATO tc
  ON tc.IDTCONTRATO = p.IDTCONTRATO
LEFT JOIN S_RANGOS_SUELDOS rs
  ON ROUND(p.SUELDO,0) BETWEEN rs.S_MIN AND rs.S_MAX;

COMMIT;


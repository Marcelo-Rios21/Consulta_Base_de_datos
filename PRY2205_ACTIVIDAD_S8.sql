CREATE SEQUENCE SEQ_CONTROL_STOCK
  START WITH 1
  INCREMENT BY 1
  NOCACHE
  NOCYCLE;
  
CREATE TABLE CONTROL_STOCK_LIBROS (
    ID_CONTROL          NUMBER(6),      
    LIBRO_ID            NUMBER(5),      
    NOMBRE_LIBRO        VARCHAR2(70),   
    TOTAL_EJEMPLARES    NUMBER(5),
    EN_PRESTAMO         NUMBER(5),
    DISPONIBLES         NUMBER(5),
    PORCENTAJE_PRESTAMO NUMBER(5,2),
    STOCK_CRITICO       CHAR(1)
);

INSERT INTO CONTROL_STOCK_LIBROS (
    ID_CONTROL,
    LIBRO_ID,
    NOMBRE_LIBRO,
    TOTAL_EJEMPLARES,
    EN_PRESTAMO,
    DISPONIBLES,
    PORCENTAJE_PRESTAMO,
    STOCK_CRITICO
)
SELECT
    SEQ_CONTROL_STOCK.NEXTVAL                AS ID_CONTROL,      
    l.LIBROID                                AS LIBRO_ID,        
    INITCAP(l.NOMBRE_LIBRO)                  AS NOMBRE_LIBRO,    
    e.total_ejemplares                       AS TOTAL_EJEMPLARES,
    NVL(p.en_prestamo, 0)                    AS EN_PRESTAMO,
    (e.total_ejemplares - NVL(p.en_prestamo, 0)) AS DISPONIBLES,

    ROUND(
        CASE
            WHEN e.total_ejemplares = 0 THEN 0
            ELSE ( NVL(p.en_prestamo, 0) / e.total_ejemplares ) * 100
        END,
        2
    )                                        AS PORCENTAJE_PRESTAMO,

    CASE
        WHEN (e.total_ejemplares - NVL(p.en_prestamo, 0)) > 2 THEN 'S'
        ELSE 'N'
    END                                      AS STOCK_CRITICO
FROM
    SN_LIBRO l

    JOIN (
        SELECT
            ej.LIBROID,
            COUNT(*) AS total_ejemplares
        FROM SN_EJEMPLAR ej
        GROUP BY ej.LIBROID
    ) e
        ON e.LIBROID = l.LIBROID

    JOIN (
        SELECT
            p.LIBROID,
            COUNT(*) AS en_prestamo
        FROM SN_PRESTAMO p
        JOIN SN_EMPLEADO emp
            ON emp.EMPLEADOID = p.EMPLEADOID
        WHERE
            emp.EMPLEADOID IN (150, 180, 190)
            AND EXTRACT(YEAR FROM p.FECHA_INICIO) =
                EXTRACT(YEAR FROM ADD_MONTHS(SYSDATE, -24))
        GROUP BY p.LIBROID
    ) p
        ON p.LIBROID = l.LIBROID;

COMMIT;


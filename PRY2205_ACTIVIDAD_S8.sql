CREATE OR REPLACE VIEW VW_DETALLE_MULTAS AS
SELECT
    p.PRESTAMOID                                             AS ID_PRESTAMO,

    INITCAP(
        a.NOMBRE || ' ' || a.APATERNO || ' ' || a.AMATERNO
    )                                                        AS NOMBRE_ALUMNO,

    INITCAP(c.DESCRIPCION)                                   AS NOMBRE_CARRERA,

    l.LIBROID                                                AS ID_LIBRO,
    l.PRECIO                                                 AS VALOR_LIBRO,

    p.FECHA_TERMINO                                          AS FECHA_TERMINO,
    p.FECHA_ENTREGA                                          AS FECHA_ENTREGA,

    TRUNC(p.FECHA_ENTREGA - p.FECHA_TERMINO)                 AS DIAS_ATRASO,

    ROUND(
        TRUNC(p.FECHA_ENTREGA - p.FECHA_TERMINO)
        * (NVL(l.PRECIO, 0) * 0.03),
        0
    )                                                        AS VALOR_MULTA,

    NVL(rm.PORC_REBAJA_MULTA, 0) / 100                       AS PORCENTAJE_REBAJA_MULTA,

    ROUND(
        ROUND(
            TRUNC(p.FECHA_ENTREGA - p.FECHA_TERMINO)
            * (NVL(l.PRECIO, 0) * 0.03),
            0
        )
        * (1 - NVL(rm.PORC_REBAJA_MULTA, 0) / 100),
        0
    )                                                        AS VALOR_REBAJADO
FROM
    SN_PRESTAMO p
    JOIN SN_LIBRO   l  ON l.LIBROID   = p.LIBROID
    JOIN SN_ALUMNO  a  ON a.ALUMNOID  = p.ALUMNOID
    JOIN SN_CARRERA c  ON c.CARRERAID = a.CARRERAID
    LEFT JOIN SN_REBAJA_MULTA rm
           ON rm.CARRERAID = c.CARRERAID
WHERE
    EXTRACT(YEAR FROM p.FECHA_TERMINO) =
        EXTRACT(YEAR FROM ADD_MONTHS(SYSDATE, -24))
    AND p.FECHA_ENTREGA > p.FECHA_TERMINO;


--CONSULTA
SELECT
    ID_PRESTAMO,
    NOMBRE_ALUMNO,
    NOMBRE_CARRERA,
    ID_LIBRO,
    VALOR_LIBRO,
    FECHA_TERMINO,
    FECHA_ENTREGA,
    DIAS_ATRASO,
    VALOR_MULTA,
    PORCENTAJE_REBAJA_MULTA,
    VALOR_REBAJADO
FROM VW_DETALLE_MULTAS
ORDER BY
    FECHA_ENTREGA DESC,
    NOMBRE_ALUMNO ASC;   

